import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const directory = fileURLToPath(new URL("../supabase/migrations/", import.meta.url));
const names = (await readdir(directory)).filter((name) => /^\d{14}_.+\.sql$/.test(name)).sort();
if (names.length === 0) throw new Error("No versioned migrations found.");
const sections = await Promise.all(names.map(async (name) => `-- Source: ${name}\n${(await readFile(join(directory, name), "utf8")).replace(/[ \t]+(?=\r?$)/gm, "")}`));
const sql = `-- GENERATED: node scripts/generate-supabase-setup.mjs
-- Sources: supabase/migrations/*.sql, in timestamp order. Do not edit this file.
-- One-time setup for a NEW project without the Nha Minh application schema.
-- No user data is deleted. Any error rolls back the entire setup.
begin;

do $setup_guard$
begin
  if exists (
    select 1 from pg_catalog.pg_tables
    where schemaname = 'public' and tablename in (
      'profiles', 'houses', 'house_members', 'pairing_invites',
      'presence_entries', 'knocks', 'notification_preferences', 'knock_dismissals'
    )
  ) then
    raise exception 'Nha Minh schema already exists. Use versioned migrations; do not rerun new-project setup.';
  end if;
end;
$setup_guard$;

${sections.join("\n\n")}

notify pgrst, 'reload schema';
commit;
`;
await writeFile(new URL("../supabase/setup-new-project.sql", import.meta.url), sql);
console.log(`Generated fresh-project setup from ${names.length} versioned migrations.`);
